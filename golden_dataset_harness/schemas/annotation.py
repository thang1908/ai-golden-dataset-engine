"""Pydantic models for annotation data contracts.

Every piece of data flowing through the pipeline is validated against these
schemas. This ensures type safety at boundaries and makes the JSON output
contract explicit and versioned.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, Field, create_model, field_validator, model_validator

from golden_dataset_harness.schemas.taxonomy import TAXONOMY, validate_attributes


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class ReviewStatus(str, Enum):
    """Human review lifecycle states."""
    AUTO_ACCEPTED = "auto_accepted"
    PENDING_REVIEW = "pending_review"
    HUMAN_APPROVED = "human_approved"
    HUMAN_REJECTED = "human_rejected"


# ---------------------------------------------------------------------------
# Core Data Models
# ---------------------------------------------------------------------------

class ImageMetadata(BaseModel):
    """Metadata about a source image."""
    image_id: str = Field(..., description="Unique identifier for the image")
    image_path: str = Field(..., description="Original file path or object key")
    width: int = Field(..., gt=0, description="Image width in pixels")
    height: int = Field(..., gt=0, description="Image height in pixels")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="When the image was ingested",
    )


class _AttributesBase(BaseModel):
    """Validate exact SigLIP codes; null is an unannotated field."""

    model_config = {"extra": "forbid", "validate_assignment": True}

    @model_validator(mode="before")
    @classmethod
    def validate_taxonomy(cls, value: Any) -> Any:
        if isinstance(value, dict):
            validate_attributes(value)
        return value


def _attribute_fields() -> dict[str, Any]:
    fields = {}
    for name, definition in TAXONOMY.items():
        value_type = Literal[tuple(definition["classes"])]
        if definition["type"] == "multi_label":
            value_type = list[value_type]
        fields[name] = (
            value_type | None,
            Field(default=None, description=definition["label"]),
        )
    return fields


# Generate typed enums and array fields from the same contract used by the VLM.
PersonAttributes = create_model(
    "PersonAttributes", __base__=_AttributesBase, __module__=__name__, **_attribute_fields(),
)


class CaptionCandidate(BaseModel):
    """A single caption generated by a VLM."""
    text: str = Field(..., min_length=1, description="The caption text")
    model_id: str = Field(..., description="ID of the model that generated this caption")
    prompt_version: str = Field(default="v1", description="Prompt template version")


class GroundingResult(BaseModel):
    """Verification result for a single claim against the image."""
    claim: str = Field(..., description="The textual claim being verified")
    supported: bool = Field(..., description="Whether the claim is supported by the image")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Verification confidence")
    reason: str = Field(default="", description="Explanation for the verdict")


class ConsensusResult(BaseModel):
    """Output of the consensus engine after clustering caption candidates."""
    caption: str = Field(..., description="The selected representative caption")
    agreement_score: float = Field(
        ..., ge=0.0, le=1.0,
        description="Mean pairwise similarity within the dominant cluster",
    )
    all_candidates: list[CaptionCandidate] = Field(
        default_factory=list,
        description="All caption candidates that fed into consensus",
    )


class QualityJudgment(BaseModel):
    """Quality evaluation from the judge agent."""
    quality_score: float = Field(
        ..., ge=0.0, le=1.0,
        description="Overall quality score (0=worst, 1=best)",
    )
    issues: list[str] = Field(
        default_factory=list,
        description="List of identified quality issues",
    )


# ---------------------------------------------------------------------------
# Top-Level Annotation Record
# ---------------------------------------------------------------------------

class AnnotationRecord(BaseModel):
    """The final, persisted annotation for a single image.

    This is the golden output of the pipeline: everything needed to reproduce
    and audit the annotation decision.
    """
    image_id: str
    image_path: str

    # Generated content
    caption: str
    attributes: PersonAttributes

    # Scores — clamped to [0, 1] by the before-validator below
    confidence: float = Field(...)
    consensus_score: float = Field(...)
    grounding_score: float = Field(...)
    judge_score: float = Field(...)

    # Provenance
    attribute_schema_version: Literal["siglip-v1"] = "siglip-v1"
    model_version: str
    prompt_version: str = "v1"
    review_status: ReviewStatus = ReviewStatus.PENDING_REVIEW
    issues: list[str] = Field(default_factory=list)

    # Timestamps
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
    )

    @field_validator("confidence", "consensus_score", "grounding_score", "judge_score", mode="before")
    @classmethod
    def clamp_scores(cls, v: float) -> float:
        """Clamp all scores to [0, 1]."""
        return max(0.0, min(1.0, float(v)))
